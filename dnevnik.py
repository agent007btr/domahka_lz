# открываем файл для записи
f = open("diary.txt", "w", encoding="utf-8")

# пишем первую строку
f.write("Сегодня мы работали с файлами Python\n")

# пишем вторую строку
f.write("Научились сохранять текст\n")

# пишем третью строку
f.write("Узнали, как читать данные обратно\n")

# закрываем файл
f.close()

# открываем файл для добавления в конец
f = open("diary.txt", "a", encoding="utf-8")

# добавляем четвертую строку
f.write("Следующее занятие - CSV и JSON\n")

# закрываем файл
f.close()

# открываем файл для чтения
f = open("diary.txt", "r", encoding="utf-8")

# читаем весь файл как одну строку
s = f.read()

# закрываем файл
f.close()

# выводим весь текст
print("Все записи:")
print(s)

# считаем количество записей вручную
n = 0
# идем по каждому символу в строке
for c in s:
    if c == "\n":
        n = n + 1
print("Количество записей:", n)